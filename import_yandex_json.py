DIFFICULTY_MAP = {
    "низкая": 1,
    "лёгкая": 1,
    "легкая": 1,
    "средняя": 3,
    "высокая": 5,
    "сложная": 5,
    "очень высокая": 5,
}


def parse_difficulty(value):
    if isinstance(value, int):
        return max(1, min(5, value))
    if isinstance(value, str):
        v = value.strip().lower()
        if v.isdigit():
            return max(1, min(5, int(v)))
        return DIFFICULTY_MAP.get(v, 4)
    return 4


def normalize_item(item: dict) -> dict:
    text = (item.get("загадка") or item.get("text") or "").strip()
    answer = (item.get("ответ") or item.get("answer") or "").strip()
    solution = (item.get("пояснение") or item.get("solution") or "").strip()
    hint = (item.get("подсказка") or item.get("hint") or "").strip()
    category = (item.get("тип") or item.get("category") or "Без категории").strip()

    alt = item.get("alt_answers") or item.get("альтернативы") or ""
    if isinstance(alt, list):
        alt = ",".join(str(a) for a in alt if a)
    alt = str(alt).strip()

    difficulty = parse_difficulty(item.get("сложность", item.get("difficulty", 4)))

    return {
        "text": text,
        "answer": answer,
        "solution": solution,
        "hint": hint,
        "category": category,
        "difficulty": difficulty,
        "alt_answers": alt,
    }


async def main():
    await init_db()

    total = len(DATA)
    added = 0
    skipped = 0
    errors = 0

    for i, item in enumerate(DATA, 1):
        norm = normalize_item(item)

        if not norm["text"] or not norm["answer"]:
            print(f"  [{i}] ❌ нет text/answer, пропуск")
            errors += 1
            continue

        ok = await add_riddle(
            text=norm["text"],
            answer=norm["answer"],
            category=norm["category"],
            difficulty=norm["difficulty"],
            source="JSON-import",
            alt_answers=norm["alt_answers"],
            solution=norm["solution"],
            hint=norm["hint"],
        )

        if ok:
            added += 1
            print(f"  [{i}] ✅ + {norm['text'][:60]}…")
        else:
            skipped += 1
            print(f"  [{i}] ⏭  дубль: {norm['text'][:60]}…")

    print("\n=== ИТОГ ===")
    print(f"Всего в списке:     {total}")
    print(f"Добавлено:          {added}")
    print(f"Пропущено (дубли):  {skipped}")
    print(f"Ошибок:             {errors}")


if __name__ == "__main__":
    asyncio.run(main())